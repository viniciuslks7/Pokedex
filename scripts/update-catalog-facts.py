"""Generate the local filter index from a pinned, public PokéAPI revision."""
import argparse
import csv
import io
import json
from pathlib import Path
import re
import subprocess
from datetime import datetime, timezone

REVISION = "2bf639e5572812a67d2b94903fdcb9d095f5aeb2"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--revision", default=REVISION)
args = parser.parse_args()
if not re.fullmatch(r"[0-9a-f]{40}", args.revision):
    parser.error("--revision must be a full Git commit hash")
source = f"https://raw.githubusercontent.com/PokeAPI/pokeapi/{args.revision}/data/v2/csv/"

def rows(filename):
    result = subprocess.run(
        ["curl", "--fail", "--silent", "--show-error", "--max-time", "30", source + filename],
        check=True, capture_output=True, text=True,
    )
    return list(csv.DictReader(io.StringIO(result.stdout)))

species = {
    int(row["id"]): [
        int(row["is_baby"]) | (int(row["is_legendary"]) << 1) | (int(row["is_mythical"]) << 2),
        int(row["habitat_id"]) if row["habitat_id"] else None,
    ] for row in rows("pokemon_species.csv")
}
stats = {}
for row in rows("pokemon_stats.csv"):
    stat_id = int(row["stat_id"])
    if 1 <= stat_id <= 6:
        values = stats.setdefault(int(row["pokemon_id"]), [None] * 6)
        values[stat_id - 1] = int(row["base_stat"])
pokemon = {}
for row in rows("pokemon.csv"):
    pokemon_id, species_id = int(row["id"]), int(row["species_id"])
    values = stats.get(pokemon_id)
    if species_id not in species or not values or any(v is None or not 0 <= v <= 255 for v in values):
        raise ValueError(f"Incomplete filter data for Pokémon {pokemon_id}")
    pokemon[pokemon_id] = [species_id, *values]
if len(species) < 1025 or len(pokemon) < len(species):
    raise ValueError("Incomplete public catalog")
data = {
    "revision": args.revision,
    "updatedAt": datetime.now(timezone.utc).date().isoformat(),
    "species": species,
    "pokemon": pokemon,
}
output = Path(__file__).resolve().parents[1] / "js" / "catalog-facts.js"
output.write_text(
    "// Generated by scripts/update-catalog-facts.py from the public PokéAPI CSV files.\n"
    "// Species: [baby/legendary/mythical bit flags, habitat ID]. Pokémon: [species ID, HP, Atk, Def, SpA, SpD, Spe].\n"
    "export const catalogFacts = " + json.dumps(data, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"Filter index: {len(species)} species and {len(pokemon)} Pokémon/forms, revision {args.revision}.")
