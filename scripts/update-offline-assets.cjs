// Generate a content revision for the installable application's complete shell.
const { readFileSync, writeFileSync, readdirSync } = require("node:fs");
const { createHash } = require("node:crypto");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
function walk(directory) {
  return readdirSync(path.join(root, directory), {
    withFileTypes: true,
  }).flatMap((entry) =>
    entry.isDirectory()
      ? walk(`${directory}/${entry.name}`)
      : [`${directory}/${entry.name}`],
  );
}
const files = [
  "index.html",
  "style.css",
  "app.webmanifest",
  ...walk("js").filter((file) => file.endsWith(".js")),
  ...walk("images").filter(
    (file) => file.endsWith(".svg") || file.startsWith("images/icons/"),
  ),
  ...walk("favicons").filter((file) => file.endsWith(".png")),
].sort();
const hash = createHash("sha256");
for (const file of [...files, "sw.js"])
  hash.update(file).update(readFileSync(path.join(root, file)));
const version = hash.digest("hex").slice(0, 16);
writeFileSync(
  path.join(root, "offline-assets.js"),
  `// Generated by scripts/update-offline-assets.cjs.\nself.POKEDEX_OFFLINE_ASSETS=${JSON.stringify({ version, files })};\n`,
);
console.log(`Offline shell: ${files.length} files, revision ${version}.`);
